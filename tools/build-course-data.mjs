import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const datasets = [
  "lesson-01/data/newstudent.csv",
  "lesson-02/data/newstudent.csv",
  "lesson-04/data/crime.csv",
  "lesson-05/data/french_names.json",
  "lesson-05/data/weather_2024.csv"
];

const entries = [];
for (const relativePath of datasets) {
  const contents = await readFile(join(root, relativePath));
  entries.push(`  ${JSON.stringify(relativePath)}: ${JSON.stringify(contents.toString("base64"))}`);
}

const output = `/* Generated by tools/build-course-data.mjs. Keeps core demos working under file://. */
(function () {
  "use strict";

  if (location.protocol !== "file:" || typeof window.fetch !== "function") return;

  const DATA = Object.freeze({
${entries.join(",\n")}
  });
  const nativeFetch = window.fetch.bind(window);
  const decoder = new TextDecoder("utf-8");

  function requestUrl(input) {
    if (typeof input === "string") return input;
    if (input instanceof URL) return input.href;
    return input && input.url ? input.url : "";
  }

  function resolveKey(input) {
    let decoded = requestUrl(input);
    try {
      decoded = new URL(decoded, document.baseURI).href;
      decoded = decodeURIComponent(decoded).replace(/\\\\/g, "/");
    } catch (_) {
      return null;
    }
    const match = decoded.match(/lesson-0([1-5])\\/data\\/([^?#]+)/i);
    return match ? \`lesson-0\${match[1]}/data/\${match[2]}\` : null;
  }

  function decodeBase64(base64) {
    const bytes = Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
    return decoder.decode(bytes);
  }

  window.fetch = function courseFetch(input, init) {
    const key = resolveKey(input);
    if (!key || !DATA[key]) return nativeFetch(input, init);
    const contentType = key.endsWith(".json")
      ? "application/json;charset=utf-8"
      : "text/csv;charset=utf-8";
    return Promise.resolve(new Response(decodeBase64(DATA[key]), {
      status: 200,
      headers: { "Content-Type": contentType }
    }));
  };
})();
`;

await writeFile(join(root, "assets/course-data.js"), output, "utf8");
console.log(`Wrote assets/course-data.js with ${datasets.length} datasets.`);
